#!/usr/bin/env node

/**
 * Pack the whole app into one self-contained HTML file.
 *
 * Input:  static/index.html            presentation shell
 *         static/pkg/wasm_frontend.js  wasm-bindgen ES-module glue
 *         static/pkg/wasm_frontend_bg.wasm
 *         static/worker.js             chunk-generation worker
 * Output: dist/vackrooms.html
 *
 * How the pieces are stitched together at runtime:
 *   - The .wasm binary travels as base64 in an inert <script type="text/plain">
 *     tag and is decoded into a blob: URL.
 *   - The glue module is embedded as a string and imported through a blob:
 *     URL, so both the page and the workers share one copy.
 *   - worker.js is rewritten to import that glue blob and init from the wasm
 *     blob; its own blob: URL is published as
 *     `globalThis.__VACKROOMS_WORKER_URL__`, which the Rust worker spawner
 *     (drivers/worker_source.rs) prefers over the sibling "worker.js" path.
 *     Where blob workers are unavailable the engine's existing in-thread
 *     generation fallback takes over.
 *
 * Run scripts/build-wasm.mjs first; this script only packages static/.
 */

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const staticDir = join(root, 'static');
const outFile = join(root, 'dist', 'vackrooms.html');

const [html, glue, worker, wasm] = await Promise.all([
  readFile(join(staticDir, 'index.html'), 'utf8'),
  readFile(join(staticDir, 'pkg', 'wasm_frontend.js'), 'utf8'),
  readFile(join(staticDir, 'worker.js'), 'utf8'),
  readFile(join(staticDir, 'pkg', 'wasm_frontend_bg.wasm')),
]);

/** Embed arbitrary source as a JS string literal that can never terminate
 *  the surrounding <script> element (every `<` becomes <). */
const jsString = (source) => JSON.stringify(source).replace(/</g, '\\u003c');

/** Replace exactly `count` occurrences, failing loudly when the source
 *  drifts and a pattern no longer matches — a silently broken bundle is
 *  worse than no bundle. */
function mustReplace(source, pattern, replacement, count = 1) {
  const matches = source.match(new RegExp(pattern.source, pattern.flags + 'g'));
  if ((matches?.length ?? 0) !== count) {
    throw new Error(
      `expected exactly ${count} match(es) of ${pattern} (found ${matches?.length ?? 0})`,
    );
  }
  return source.replace(pattern, replacement);
}

// Worker: import the shared glue blob, init from the wasm blob. The
// placeholders are substituted with live blob: URLs by the page bootstrap.
let workerSrc = mustReplace(
  worker,
  /from "\.\/pkg\/wasm_frontend\.js"/,
  'from "__GLUE_URL__"',
);
workerSrc = mustReplace(
  workerSrc,
  /wasmReady = init\(\)/,
  'wasmReady = init({ module_or_path: "__WASM_URL__" })',
);

const bootstrap = `
        // ---- Single-file bootstrap (generated by build-single-file.mjs) ----
        const __b64 = document.getElementById('vackrooms-wasm').textContent;
        const __bytes = Uint8Array.from(atob(__b64.replace(/\\s+/g, '')), (c) => c.charCodeAt(0));
        const __blobUrl = (parts, type) => URL.createObjectURL(new Blob(parts, { type }));
        const __wasmUrl = __blobUrl([__bytes], 'application/wasm');
        const __glueUrl = __blobUrl([${jsString(glue)}], 'text/javascript');
        globalThis.__VACKROOMS_WORKER_URL__ = __blobUrl([
            ${jsString(workerSrc)}
                .replaceAll('__GLUE_URL__', __glueUrl)
                .replaceAll('__WASM_URL__', __wasmUrl),
        ], 'text/javascript');
        const { default: __wbgInit,`;

// Page: swap the static ESM import for the glue blob, and make the bare
// `init()` call at the bottom of the shell resolve to the embedded binary
// (argument-less init would try `new URL(..., import.meta.url)` against a
// blob: base and throw).
let page = mustReplace(
  html,
  /import init, \{/,
  bootstrap.trimStart(),
);
page = mustReplace(
  page,
  /\} from '\.\/pkg\/wasm_frontend\.js';/,
  "} = await import(__glueUrl);\n        const init = () => __wbgInit({ module_or_path: __wasmUrl });",
);

// Base64 payload sits in an inert tag so the module script stays readable.
const wasmB64 = wasm.toString('base64');
page = mustReplace(
  page,
  /    <script type="module">/,
  `    <script type="text/plain" id="vackrooms-wasm">${wasmB64}</script>\n    <script type="module">`,
);

await mkdir(dirname(outFile), { recursive: true });
await writeFile(outFile, page);
console.log(
  `wrote ${outFile} (${(page.length / 1024 / 1024).toFixed(2)} MiB, wasm ${(wasm.length / 1024).toFixed(0)} KiB)`,
);
